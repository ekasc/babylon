// crashes on unexpected input.
//
// The font is intentionally compact and self-contained: no font file, no
// native dependency, no network. It is sufficient for rendering the
// deterministic transcript text that Snapcompact produces. Critical exact
// tokens (paths, shas, identifiers) are preserved as raw text in the
// dictionary, not rasterized, so OCR imperfections on this font cannot
// erase the strings a coding agent must retrieve verbatim.

